import { createHash } from 'node:crypto'
import { mkdir, readdir, rename, stat, unlink, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

/**
 * agy agent template carrying DSH's system prompt and tool contract.
 *
 * Why a template and not the user message:
 * - `excludeDefaultComponents: true` is what removes agy's ~60 built-in tools and its default
 *   agent instructions (measured on agy 1.5.9: 9,488 → 415 input tokens for the same prompt). Deny
 *   rules alone leave the tools visible; the model then tries them and agy forces a retry.
 * - agy truncates a long user message; a template body is read whole (150 KB verified). Keeping the
 *   bulky, stable part here leaves the user message for the conversation only.
 *
 * The file name is a hash of the body, so every turn of one conversation reuses one file.
 */

export const AGY_TEMPLATE_PREFIX = 'dsh-agy-'
const KEEP_TEMPLATES = 16

function frontMatter(name: string): string {
  return [
    '---',
    `name: ${name}`,
    'description: DSH text model backend (generated by dsh-antigravity-oauth).',
    'excludeDefaultComponents: true',
    'tools: []',
    'mainAgent: true',
    'subagent: false',
    'model: inherit',
    'commandExecutionPolicy: off',
    'mcpServers: []',
    'skills: []',
    'plugins: []',
    '---',
    '',
  ].join('\n')
}

export function templateName(body: string): string {
  return AGY_TEMPLATE_PREFIX + createHash('sha256').update(body).digest('hex').slice(0, 16)
}

/** Directory agy scans for workspace agents. */
export function templateDir(workspace: string): string {
  return join(workspace, '.agents', 'agents')
}

/** Write the template if it is not there yet; return its agent name. */
export async function ensureTemplate(workspace: string, body: string): Promise<string> {
  const name = templateName(body)
  const dir = templateDir(workspace)
  const file = join(dir, `${name}.md`)
  try {
    await stat(file)
    return name
  } catch { /* write it below */ }
  await mkdir(dir, { recursive: true, mode: 0o700 })
  const tmp = `${file}.${process.pid}.tmp`
  await writeFile(tmp, frontMatter(name) + body + '\n', { mode: 0o600 })
  await rename(tmp, file)
  await pruneTemplates(dir).catch(() => undefined)
  return name
}

/** Keep the newest templates; each conversation's system prompt makes a new one. */
async function pruneTemplates(dir: string): Promise<void> {
  const names = (await readdir(dir)).filter(n => n.startsWith(AGY_TEMPLATE_PREFIX) && n.endsWith('.md'))
  if (names.length <= KEEP_TEMPLATES) return
  const dated = await Promise.all(names.map(async n => ({ n, t: (await stat(join(dir, n))).mtimeMs })))
  dated.sort((a, b) => b.t - a.t)
  await Promise.all(dated.slice(KEEP_TEMPLATES).map(({ n }) => unlink(join(dir, n)).catch(() => undefined)))
}
